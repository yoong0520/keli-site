def main(folder):
    for cid, o in C.items():
        fp = os.path.join(folder, cid + '.json')
        if not os.path.exists(fp) or not o: continue
        j = json.load(open(fp, encoding='utf-8'))
        orig = j.get('results') or []
        for k in ('grade', 'credits', 'students', 'course_type'):
            if o.get(k): j[k] = o[k]
        if o.get('summary'): j['summary'] = o['summary']
        rows = [{'item': a, 'value': b} for a, b in o.get('rows', [])]
        rows += [{'item': a, 'value': b} for a, b in rows_from(orig, *o.get('keep', []))]
        if rows: j['results'] = rows
