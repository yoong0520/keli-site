def rows_from(orig, *names):
    """원본 results 에서 item 이름이 names 로 시작하는 행을 찾아 (item, value) 로."""
    out = []
    for n in names:
        for r in orig:
            if isinstance(r, dict) and r.get('item', '').startswith(n) and r.get('value'):
                out.append((n.split('(')[0], r['value'])); break
    return out

